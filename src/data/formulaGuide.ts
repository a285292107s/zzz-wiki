export type Expr =
  | { k: 'var'; text: string; sub?: string }
  | { k: 'num'; text: string }
  | { k: 'op'; text: string }
  | { k: 'when'; text: string }
  | { k: 'grp'; items: Expr[] }
  | { k: 'frac'; num: Expr[]; den: Expr[] }

const sym = (text: string, sub?: string): Expr => ({ k: 'var', text, sub })
const lit = (text: string | number): Expr => ({ k: 'num', text: String(text) })
const op = (text: string): Expr => ({ k: 'op', text })
const when = (text: string): Expr => ({ k: 'when', text })
const grp = (...items: Expr[]): Expr => ({ k: 'grp', items })
const frac = (num: Expr[], den: Expr[]): Expr => ({ k: 'frac', num, den })
const mul = (items: Expr[]): Expr[] => items.flatMap((x, i) => (i === 0 ? [x] : [op('×'), x]))

